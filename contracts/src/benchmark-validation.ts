import { Ajv } from 'ajv';
import type { BenchmarkRun } from './benchmark.js';

/** 严格校验导入的嵌套数组，拒绝空结果、未知版本及伪造的顶层通过标志。 */
export const validateBenchmarkRun = new Ajv({
  allErrors: true,
  strict: false,
}).compile<BenchmarkRun>({
  type: 'object',
  additionalProperties: false,
  required: [
    'schemaVersion',
    'suite',
    'id',
    'createdAt',
    'source',
    'environment',
    'config',
    'mode',
    'cases',
  ],
  properties: {
    archiveRecovery: {
      type: 'object',
      additionalProperties: false,
      required: ['recoveredAt', 'originalSha256', 'reason'],
      properties: {
        recoveredAt: { type: 'string' },
        originalSha256: { type: 'string', pattern: '^[a-f0-9]{64}$' },
        reason: { type: 'string' },
      },
    },
    schemaVersion: { enum: [1, 2] },
    suite: { type: 'string', minLength: 1 },
    id: { type: 'string', minLength: 1 },
    createdAt: { type: 'string', minLength: 1 },
    completedAt: { type: ['string', 'null'] },
    mode: { enum: ['scripted', 'real', 'deployed'] },
    release: { type: 'object' },
    origin: { enum: ['local', 'ci', 'deployed'] },
    deploymentEnvironment: { type: 'string', minLength: 1, maxLength: 160 },
    runtime: {
      type: 'object',
      additionalProperties: false,
      required: [
        'ready',
        'engineVersion',
        'chromeVersion',
        'hostSha256',
        'engineSha256',
      ],
      properties: {
        ready: { type: 'boolean' },
        engineVersion: { type: 'string' },
        chromeVersion: { type: 'string' },
        hostSha256: { type: 'string' },
        engineSha256: { type: 'string' },
      },
    },
    modelConfiguration: {
      type: 'object',
      additionalProperties: false,
      required: [
        'vision',
        'tokenParameter',
        'maxTokens',
        'thinking',
        'reasoningEffort',
        'endpointFingerprint',
        'modelMs',
      ],
      properties: {
        name: { type: 'string', minLength: 1, maxLength: 160 },
        baseUrl: {
          type: 'string',
          maxLength: 2048,
          pattern: '^https?://[^/?#@\\s]+(?:/[^?#\\s]*)?$',
        },
        vision: { type: 'boolean' },
        tokenParameter: { type: 'string' },
        maxTokens: { type: 'integer', minimum: 1 },
        thinking: { type: 'string' },
        reasoningEffort: { type: 'string' },
        endpointFingerprint: { type: 'string' },
        modelMs: { type: 'integer', minimum: 1 },
      },
    },
    source: {
      type: 'object',
      required: ['revision', 'dirty'],
      additionalProperties: false,
      properties: {
        revision: { type: 'string', minLength: 1 },
        dirty: { type: 'boolean' },
        fingerprint: { type: 'string', pattern: '^[a-f0-9]{64}$' },
      },
    },
    environment: {
      type: 'object',
      required: ['node', 'platform', 'arch'],
      additionalProperties: false,
      properties: {
        node: { type: 'string' },
        platform: { type: 'string' },
        arch: { type: 'string' },
      },
    },
    config: {
      type: 'object',
      required: ['model', 'maxContextChars', 'maxTurns'],
      additionalProperties: false,
      properties: {
        model: { type: 'string' },
        maxContextChars: { type: 'integer', minimum: 1 },
        maxTurns: { type: 'integer', minimum: 1 },
      },
    },
    cases: {
      type: 'array',
      minItems: 1,
      maxItems: 100,
      items: {
        type: 'object',
        additionalProperties: false,
        required: [
          'id',
          'name',
          'scope',
          'elapsedMs',
          'verdict',
          'checks',
          'calls',
          'commands',
        ],
        properties: {
          preflight: {
            type: 'object',
            additionalProperties: false,
            required: ['version', 'status', 'gaps'],
            properties: {
              version: { type: 'string', minLength: 1 },
              status: { enum: ['SUPPORTED', 'BLOCKED'] },
              executionPolicy: { const: 'skip-steps' },
              gaps: {
                type: 'array',
                maxItems: 300,
                items: {
                  type: 'object',
                  additionalProperties: false,
                  required: [
                    'capability',
                    'capabilityName',
                    'stepId',
                    'requirement',
                    'reason',
                  ],
                  properties: Object.fromEntries(
                    [
                      'capability',
                      'capabilityName',
                      'stepId',
                      'requirement',
                      'reason',
                    ].map((key) => [key, { type: 'string', minLength: 1 }]),
                  ),
                },
              },
            },
          },
          id: { type: 'string', minLength: 1 },
          name: { type: 'string' },
          scope: { type: 'string' },
          elapsedMs: { type: 'number', minimum: 0 },
          verdict: { type: 'string' },
          browserResult: {
            type: 'object',
            additionalProperties: false,
            required: ['outcome', 'output', 'evidenceRefs'],
            properties: {
              outcome: { enum: ['COMPLETED', 'INCOMPLETE'] },
              output: { type: 'string' },
              evidenceRefs: { type: 'array', items: { type: 'string' } },
            },
          },
          verification: {
            type: 'object',
            additionalProperties: false,
            required: [
              'sourceTaskId',
              'sourceCreatedAt',
              'sourceDefinitionSha256',
              'historicalVerdict',
              'task',
              'steps',
              'report',
              'sessionClosed',
            ],
            properties: {
              sourceTaskId: { type: 'string', minLength: 1 },
              sourceCreatedAt: { type: 'string', minLength: 1 },
              sourceDefinitionSha256: {
                type: 'string',
                pattern: '^[a-f0-9]{64}$',
              },
              historicalVerdict: { type: 'string' },
              task: { type: 'object' },
              steps: {
                type: 'array',
                maxItems: 64,
                items: {
                  type: 'object',
                  required: ['stepId', 'status', 'summary'],
                  properties: {
                    stepId: { type: 'string', minLength: 1 },
                    status: {
                      enum: [
                        'PENDING',
                        'RUNNING',
                        'COMPLETED',
                        'BLOCKED',
                        'ERROR',
                        'SKIPPED',
                      ],
                    },
                    summary: { type: 'string' },
                  },
                },
              },
              report: { type: ['object', 'null'] },
              sessionClosed: { type: 'boolean' },
            },
          },
          modelConfiguration: { $ref: '#/properties/modelConfiguration' },
          deployment: {
            type: 'object',
            additionalProperties: false,
            required: ['api', 'agent', 'node', 'executionId'],
            properties: {
              api: { type: ['object', 'null'] },
              agent: { type: ['object', 'null'] },
              node: { type: ['object', 'null'] },
              executionId: { type: ['string', 'null'] },
            },
          },
          facts: {
            type: 'object',
            additionalProperties: false,
            required: ['visits', 'writes', 'sessionClosed', 'injected'],
            properties: {
              visits: { type: 'integer', minimum: 0 },
              writes: { type: 'array', items: { type: 'object' } },
              sessionClosed: { type: 'boolean' },
              injected: { type: 'boolean' },
            },
          },
          checks: {
            type: 'array',
            minItems: 1,
            items: {
              type: 'object',
              additionalProperties: false,
              required: ['name', 'passed', 'detail'],
              properties: {
                name: { type: 'string' },
                passed: { type: 'boolean' },
                detail: { type: 'string' },
              },
            },
          },
          commands: {
            type: 'array',
            maxItems: 1000,
            items: {
              type: 'object',
              additionalProperties: false,
              required: ['decisionIndex', 'operation', 'status', 'effect'],
              properties: {
                decisionIndex: { type: 'integer', minimum: 0 },
                callId: { type: 'string', minLength: 1 },
                stepId: { type: 'string', minLength: 1 },
                operation: { type: 'object' },
                status: { type: 'string' },
                effect: { type: 'string' },
                result: { type: 'object' },
                error: { type: 'string' },
                origin: { type: 'string' },
                fault: { type: 'string' },
                nativeStatus: { type: 'string' },
              },
            },
          },
          calls: {
            type: 'array',
            maxItems: 1000,
            items: {
              type: 'object',
              required: [
                'id',
                'callIndex',
                'decisionIndex',
                'model',
                'purpose',
                'startedAt',
                'finishedAt',
                'status',
                'request',
                'response',
                'requestSha256',
                'error',
                'promptTokens',
                'completionTokens',
                'elapsedMs',
                'imagesOmitted',
                'archived',
              ],
              properties: {
                id: { type: 'string' },
                callIndex: { type: 'integer', minimum: 1 },
                decisionIndex: { type: 'integer', minimum: 1 },
                model: { type: 'string' },
                purpose: { enum: ['DECISION', 'FIELD_VALUE'] },
                startedAt: { type: 'string' },
                finishedAt: { type: ['string', 'null'] },
                status: { enum: ['PENDING', 'RECEIVED', 'ERROR'] },
                request: { type: ['string', 'null'] },
                response: { type: ['string', 'null'] },
                requestSha256: { type: 'string' },
                error: { type: ['string', 'null'] },
                archived: { type: 'boolean' },
                stepId: { type: 'string' },
                promptTokens: { type: ['integer', 'null'], minimum: 0 },
                completionTokens: { type: ['integer', 'null'], minimum: 0 },
                elapsedMs: { type: ['number', 'null'], minimum: 0 },
                imagesOmitted: { type: 'integer', minimum: 0 },
              },
            },
          },
        },
      },
    },
  },
  allOf: [
    {
      if: { properties: { suite: { const: 'agent-loop-v2-live-v1' } } },
      then: {
        properties: {
          mode: { const: 'real' },
          cases: { items: { required: ['verification'] } },
        },
      },
    },
    {
      if: { properties: { suite: { const: 'agent-loop-v2-deployed-v1' } } },
      then: {
        properties: {
          mode: { const: 'deployed' },
          cases: { items: { required: ['verification', 'deployment'] } },
        },
      },
    },
    {
      if: { properties: { schemaVersion: { const: 2 } } },
      then: { required: ['release', 'origin'] },
    },
    {
      if: { properties: { mode: { const: 'real' } } },
      then: {
        required: ['runtime', 'modelConfiguration', 'completedAt'],
        properties: { source: { required: ['fingerprint'] } },
      },
    },
  ],
});
